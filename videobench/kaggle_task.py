"""Build a self-contained Kaggle Benchmarks task that runs the comprehension test on one video.

Same protocol as videobench.comprehension (matched / control frames with an explicit "not shown"
option, plus the planted-false-fact canary), with every frame set sent as one grid image.
Run ON Kaggle, Claude / Gemini / Gemma truly see base64 images (verified by
kaggle/grounding/media_grounding.py); the local model proxy silently drops them.

  python -m videobench.kaggle_task <task-id> <video.mp4> <label> [--out kaggle/comp]
  kaggle b t push hrsu-comp-<task-id>-<label> -f kaggle/comp/<file>.py --wait
  kaggle b t run  hrsu-comp-<task-id>-<label> -m gemini-3.8-flash -m gemma-4-31b-it ...
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import tempfile
from pathlib import Path

from PIL import Image

from . import comprehension as C

TEMPLATE = '''"""HRSU-VideoBench comprehension: {task_id} / {label} (generated by videobench.kaggle_task).

conveyed = right answers from the beat's own frames; leakage = answers other than "not shown"
on a fixed foreign control; comprehension = conveyed - leakage. Canary: a planted false label on
the hook frames must be followed, while the truth is given without video.
"""
import random

import kaggle_benchmarks as kbench
from kaggle_benchmarks.content_types import images

QUIZ = {quiz}
GRIDS = {grids}
CONTROL_GRID = "{control_grid}"
CANARY_GRID = "{canary_grid}"
REPS = {reps}
LETTERS = "ABCDE"
NOT_SHOWN = "Not shown in these frames"


def options_for(item, rng, with_not_shown):
    opts = [item["answer"], *([item["planted"]] if "planted" in item else []), *item["distractors"]]
    rng.shuffle(opts)
    return opts + [NOT_SHOWN] if with_not_shown else opts


def prompt_for(frames, item, options):
    opts = "\\n".join(f"{{LETTERS[i]}}) {{o}}" for i, o in enumerate(options))
    if frames:
        lead = ("The image is a grid of frames (left-to-right, top-to-bottom) from one segment of "
                "a MUTED explainer video. Answer ONLY from what these frames show. If the frames "
                "do not show the answer, choose \\"" + NOT_SHOWN + "\\" -- even if you know the "
                "answer from elsewhere.")
    else:
        lead = "Answer this question about an industrial chemistry topic."
    return (lead + "\\n\\nQuestion: " + item["q"] + "\\n" + opts
            + "\\n\\nEnd your reply with a line of the form ANSWER: <letter>.")


def ask(llm, name, frames_b64, item, options):
    import re
    with kbench.chats.new(name):
        kw = {{"image": images.from_base64(frames_b64, format="jpeg")}} if frames_b64 else {{}}
        reply = llm.prompt(prompt_for(bool(frames_b64), item, options), **kw)
    m = re.findall(r"ANSWER:\\s*\\(?([A-E])\\)?", reply or "", flags=re.I)
    i = LETTERS.find(m[-1].upper()) if m else -1
    return options[i] if 0 <= i < len(options) else ""


@kbench.task(name="hrsu-comp-{task_id}-{label}",
             description="HRSU-VideoBench comprehension of {task_id} video '{label}'")
def comprehension(llm) -> dict:
    rng = random.Random(7)
    n = right = leak = prior = 0
    for q in QUIZ["questions"]:
        for rep in range(REPS):
            n += 1
            prior += ask(llm, f"{{q['id']}}-{{rep}}-none", "", q,
                         options_for(q, rng, False)) == q["answer"]
            right += ask(llm, f"{{q['id']}}-{{rep}}-matched", GRIDS[q["beat"]], q,
                         options_for(q, rng, True)) == q["answer"]
            leak += ask(llm, f"{{q['id']}}-{{rep}}-control", CONTROL_GRID, q,
                        options_for(q, rng, True)) != NOT_SHOWN
    c = QUIZ["canary"]
    truth = follows = 0
    for rep in range(REPS):
        truth += ask(llm, f"canary-{{rep}}-none", "", c, options_for(c, rng, False)) == c["answer"]
        follows += ask(llm, f"canary-{{rep}}-planted", CANARY_GRID, c,
                       options_for(c, rng, True)) == c["planted"]
    grounded = truth / REPS >= 0.5 and follows / REPS >= 0.5
    kbench.assertions.assert_true(grounded, expectation=(
        f"viewer is grounded: truth without video {{truth}}/{{REPS}}, "
        f"follows planted frames {{follows}}/{{REPS}}"))
    conveyed, leakage = round(right / n, 3), round(leak / n, 3)
    return {{"conveyed": conveyed, "leakage": leakage,
            "comprehension": round(conveyed - leakage, 3), "prior": round(prior / n, 3),
            "canary_truth_without_video": round(truth / REPS, 3),
            "canary_follows_planted_frames": round(follows / REPS, 3), "grounded": grounded}}


comprehension.run(kbench.llm)
'''


def grid_b64(frames: list[Path], cols: int = 3, width: int = 960) -> str:
    ims = [Image.open(p).convert("RGB") for p in frames]
    w, h = ims[0].size
    rows = -(-len(ims) // cols)
    sheet = Image.new("RGB", (w * cols, h * rows), (10, 25, 47))
    for i, im in enumerate(ims):
        sheet.paste(im.resize((w, h)), ((i % cols) * w, (i // cols) * h))
    sheet.thumbnail((width, width * 2))
    buf = io.BytesIO()
    sheet.save(buf, "JPEG", quality=82)
    return base64.b64encode(buf.getvalue()).decode()


def build(task_id: str, video: Path, label: str, reps: int = 2) -> str:
    t = C.task(task_id)
    run_dir = C.ROOT / t["run"]
    qz = C.quiz(task_id)
    windows = C.beat_windows(run_dir)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        grids = {b: grid_b64(C.extract_frames(video, *windows[b], tmp / b, C.FRAMES_PER_BEAT))
                 for b in sorted({q["beat"] for q in qz["questions"]})}
        control_grid = grid_b64(C.control_frames(qz, tmp / "control"))
        c = qz["canary"]
        hook = C.extract_frames(video, *windows[c["beat"]], tmp / "canary_src", C.FRAMES_PER_BEAT)
        canary_grid = grid_b64(C.plant_label(hook, c["planted_label"], tmp / "canary"))
    return TEMPLATE.format(task_id=task_id, label=label, reps=reps,
                           quiz=json.dumps({"questions": qz["questions"], "canary": c}, indent=1),
                           grids=json.dumps(grids), control_grid=control_grid,
                           canary_grid=canary_grid)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("task")
    ap.add_argument("video", type=Path)
    ap.add_argument("label")
    ap.add_argument("--reps", type=int, default=2)
    ap.add_argument("--out", type=Path, default=C.ROOT / "kaggle" / "comp")
    a = ap.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    path = a.out / f"comp_{a.task.replace('-', '_')}_{a.label.replace('-', '_')}.py"
    path.write_text(build(a.task, a.video, a.label, a.reps), encoding="utf-8")
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
