"""Build a self-contained Kaggle Benchmarks task that runs the comprehension test on one video.

Frames are what make media judgments trustworthy: run ON Kaggle, Claude / Gemini / Gemma truly
see base64 images (verified by kaggle/grounding/media_grounding.py), whereas the local model
proxy silently drops them. Each beat's frames go in as one 2x3 grid image, cropped above the
caption band exactly like videobench.comprehension, with the quiz embedded.

  python -m videobench.kaggle_task <task-id> <video.mp4> <label> [--out kaggle/comp]
  kaggle b t push hrsu-comp-<task-id>-<label> -f kaggle/comp/<file>.py --wait
  kaggle b t run  hrsu-comp-<task-id>-<label> -m gemini-3.6-flash -m claude-sonnet-5-5-default ...
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import tempfile
from pathlib import Path

from PIL import Image

from . import comprehension as C

TEMPLATE = '''"""HRSU-VideoBench comprehension: {task_id} / {label} (generated by videobench.kaggle_task).

Scores how much of a verified explanation a viewer model gets from the video. Conditions:
none (no video: prior knowledge), visual (beat frames, muted, captions cropped away),
both (frames + narration). visual_lift = acc(visual) - acc(none).
"""
import random
import re

import kaggle_benchmarks as kbench
from kaggle_benchmarks.content_types import images

QUIZ = {quiz}
NARRATION = {narration}
GRIDS = {grids}
CANARY = {canary}
CANARY_GRID = "{canary_grid}"
REPS = {reps}
LETTERS = "ABCD"


def prompt_for(cond, q, options, narration=None):
    opts = "\\n".join(f"{{LETTERS[i]}}) {{o}}" for i, o in enumerate(options))
    if cond == "none":
        lead = "Answer this question about an industrial chemistry topic."
    elif cond == "visual":
        lead = ("The image is a grid of frames (read left-to-right, top-to-bottom) from one segment "
                "of a MUTED explainer video with no captions. Answer using what the visuals show; "
                "if they do not show it, give your best guess.")
    else:
        lead = ("The image is a grid of frames (read left-to-right, top-to-bottom) from one segment "
                "of an explainer video. The narrator says during it: \\"" + (narration or NARRATION[q["beat"]])
                + "\\" Answer using the video.")
    return (lead + "\\n\\nQuestion: " + q["q"] + "\\n" + opts
            + "\\n\\nEnd your reply with a line of the form ANSWER: <letter>.")


def letter(reply):
    m = re.findall(r"ANSWER:\\s*\\(?([ABCD])\\)?", reply or "", flags=re.I)
    return m[-1].upper() if m else ""


@kbench.task(name="hrsu-comp-{task_id}-{label}",
             description="HRSU-VideoBench comprehension of {task_id} video '{label}'")
def comprehension(llm) -> dict:
    rng = random.Random(7)
    right = {{"none": 0, "visual": 0, "both": 0}}
    total = {{"none": 0, "visual": 0, "both": 0}}
    for q in QUIZ["questions"]:
        for rep in range(REPS):
            options = [q["answer"], *q["distractors"]]
            rng.shuffle(options)
            correct = LETTERS[options.index(q["answer"])]
            for cond in ("none", "visual", "both"):
                with kbench.chats.new(f"{{q['id']}}-{{rep}}-{{cond}}"):
                    kw = {{}} if cond == "none" else {{
                        "image": images.from_base64(GRIDS[q["beat"]], format="jpeg")}}
                    ans = letter(llm.prompt(prompt_for(cond, q, options), **kw))
                total[cond] += 1
                right[cond] += ans == correct
    acc = {{c: round(right[c] / total[c], 3) for c in right}}

    # Canary (anti-cheating): a FALSE fact is drawn onto the hook frames (and said in the
    # narration for "both"). Grounded = real answer without video, planted answer with it.
    expect = {{"none": CANARY["answer"], "visual": CANARY["planted"], "both": CANARY["planted"]}}
    hits = {{"none": 0, "visual": 0, "both": 0}}
    for rep in range(REPS):
        options = [CANARY["answer"], CANARY["planted"], *CANARY["distractors"]]
        rng.shuffle(options)
        for cond in ("none", "visual", "both"):
            with kbench.chats.new(f"canary-{{rep}}-{{cond}}"):
                kw = {{}} if cond == "none" else {{
                    "image": images.from_base64(CANARY_GRID, format="jpeg")}}
                ans = letter(llm.prompt(prompt_for(cond, CANARY, options,
                                                   CANARY["planted_narration"]), **kw))
            hits[cond] += ans != "" and options[LETTERS.index(ans)] == expect[cond]
    canary = {{c: round(hits[c] / REPS, 3) for c in hits}}
    grounded = all(v >= 0.5 for v in canary.values())
    kbench.assertions.assert_true(grounded, expectation=f"viewer is grounded (canary): {{canary}}")
    return {{"acc_none": acc["none"], "acc_visual": acc["visual"], "acc_both": acc["both"],
            "visual_lift": round(acc["visual"] - acc["none"], 3),
            "canary_truth_without_video": canary["none"],
            "canary_follows_planted_visual": canary["visual"],
            "canary_follows_planted_both": canary["both"], "grounded": grounded}}


comprehension.run(kbench.llm)
'''


def grid_b64(frames: list[Path], cols: int = 3, width: int = 960) -> str:
    ims = [Image.open(p).convert("RGB") for p in frames]
    w, h = ims[0].size
    rows = -(-len(ims) // cols)
    sheet = Image.new("RGB", (w * cols, h * rows), (10, 25, 47))
    for i, im in enumerate(ims):
        sheet.paste(im.resize((w, h)), ((i % cols) * w, (i // cols) * h))
    sheet.thumbnail((width, width * 2))
    buf = io.BytesIO()
    sheet.save(buf, "JPEG", quality=82)
    return base64.b64encode(buf.getvalue()).decode()


def build(task_id: str, video: Path, label: str, reps: int = 2) -> str:
    t = C.task(task_id)
    run_dir = C.ROOT / t["run"]
    quiz = json.loads((C.QUIZZES / f"{task_id}.json").read_text(encoding="utf-8"))
    windows, narr = C.beat_windows(run_dir), C.beat_narration(run_dir)
    beats = sorted({q["beat"] for q in quiz["questions"]})
    grids = {}
    with tempfile.TemporaryDirectory() as tmp:
        for b in beats:
            grids[b] = grid_b64(C.extract_frames(video, *windows[b], Path(tmp) / b,
                                                 C.FRAMES_PER_BEAT))
        c = quiz["canary"]
        src = C.extract_frames(video, *windows[c["beat"]], Path(tmp) / "canary_src",
                               C.FRAMES_PER_BEAT)
        canary_grid = grid_b64(C.plant_label(src, c["planted_label"], Path(tmp) / "canary"))
    return TEMPLATE.format(task_id=task_id, label=label, reps=reps,
                           canary=json.dumps(c, indent=1), canary_grid=canary_grid,
                           quiz=json.dumps({"questions": quiz["questions"]}, indent=1),
                           narration=json.dumps({b: narr[b] for b in beats}, indent=1),
                           grids=json.dumps(grids))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("task")
    ap.add_argument("video", type=Path)
    ap.add_argument("label")
    ap.add_argument("--reps", type=int, default=2)
    ap.add_argument("--out", type=Path, default=C.ROOT / "kaggle" / "comp")
    a = ap.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    path = a.out / f"comp_{a.task.replace('-', '_')}_{a.label.replace('-', '_')}.py"
    path.write_text(build(a.task, a.video, a.label, a.reps), encoding="utf-8")
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
